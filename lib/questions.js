export const ALL_QS = SECTIONS.flatMap((s) => s.qs);

/** Человекочитаемый текст брифа — для Telegram и для кнопки «Скопировать». */
export function renderText(payload) {
  const { who = '', contact = '', answers = {} } = payload || {};
  const lines = ['БРИФ · ЭТАП 1 · ЕДИНЫЙ ИНБОКС', ''];
  if (who) lines.push('Заполнил: ' + who);
  if (contact) lines.push('Связь: ' + contact);
  lines.push('Дата: ' + new Date().toLocaleString('ru-RU'), '');

  let n = 0;
  SECTIONS.forEach((s, si) => {
    lines.push(`${si + 1}. ${s.title.toUpperCase()}`);
    s.qs.forEach((q) => {
      n++;
      const a = answers[q.id] || {};
      const chosen = Array.isArray(a.c) ? a.c : [];
      const text = typeof a.t === 'string' ? a.t.trim() : '';
      lines.push(`${n}) ${q.t}`);
      if (q.opts) lines.push('   Выбрано: ' + (chosen.length ? chosen.join(', ') : '—'));
      lines.push('   Ответ: ' + (text ? text.replace(/\n/g, '\n          ') : '—'));
    });
    lines.push('');
  });
  return lines.join('\n');
}

/** Сколько вопросов реально заполнено. */
export function countAnswered(answers = {}) {
  return ALL_QS.filter((q) => {
    const a = answers[q.id] || {};
    return (Array.isArray(a.c) && a.c.length) || (typeof a.t === 'string' && a.t.trim());
  }).length;
}
